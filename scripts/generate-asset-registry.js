// Builds src/content/assetRegistry.ts: React Native needs every bundled file
// referenced with a literal require(), so this lists everything under assets/audio and assets/images.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const roots = ['audio', 'images'];
const exts = new Set(['.png', '.ogg', '.mp3', '.wav', '.jpg']);
const skip = new Set(['icon.png', 'splash-icon.png', 'android-icon-foreground.png',
  'android-icon-background.png', 'android-icon-monochrome.png']);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (exts.has(path.extname(e.name)) && !skip.has(e.name)) {
      files.push(path.relative(path.join(root, 'assets'), p).split(path.sep).join('/'));
    }
  }
})(path.join(root, 'assets'));
files.sort();
const lines = files.filter((f) => roots.includes(f.split('/')[0]))
  .map((f) => `  '${f}': require('../../assets/${f}'),`);
fs.writeFileSync(path.join(root, 'src/content/assetRegistry.ts'),
  `// GENERATED by scripts/generate-asset-registry.js (npm run assets). Do not edit.\n` +
  `export const assetRegistry: Record<string, number> = {\n${lines.join('\n')}\n};\n`);
console.log(`registry: ${lines.length} files`);
